/**
 * Pemetaan icon kategori secara otomatis bila icon di DB masih berisi emoji
 */
function category_icon_svg($cat_slug_or_name, $size = 18, $class = '') {
    $str = strtolower((string)$cat_slug_or_name);
    if (strpos($str, 'tekno') !== false || strpos($str, 'program') !== false || strpos($str, 'code') !== false) {
        return icon('code', $class, $size);
    } elseif (strpos($str, 'desain') !== false || strpos($str, 'kreatif') !== false || strpos($str, 'ui') !== false) {
        return icon('palette', $class, $size);
    } elseif (strpos($str, 'bahasa') !== false || strpos($str, 'lang') !== false) {
        return icon('languages', $class, $size);
    } elseif (strpos($str, 'bisnis') !== false || strpos($str, 'karir') !== false || strpos($str, 'biz') !== false) {
        return icon('briefcase', $class, $size);
    } elseif (strpos($str, 'akademik') !== false || strpos($str, 'kuliah') !== false) {
        return icon('graduation-cap', $class, $size);
    } elseif (strpos($str, 'media') !== false || strpos($str, 'audio') !== false || strpos($str, 'video') !== false) {
        return icon('video', $class, $size);
    }
    return icon('lightbulb', $class, $size);
}

/**
 * Pemetaan icon badge gamifikasi secara otomatis (menggantikan emoji badge)
 */
function badge_icon_svg($badge_name, $size = 20, $class = '') {
    $n = strtolower((string)$badge_name);
    if (strpos($n, 'mentor') !== false || strpos($n, 'sdg') !== false) {
        return icon('shield-check', $class, $size);
    } elseif (strpos($n, 'master') !== false) {
        return icon('trophy', $class, $size);
    } elseif (strpos($n, 'mahir') !== false) {
        return icon('award', $class, $size);
    }
    return icon('coins', $class, $size);
}
